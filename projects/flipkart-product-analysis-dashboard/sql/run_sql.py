"""
Loads the Flipkart-style data into PostgreSQL and runs the 14 SQL queries.

  1. schema.sql  - products and orders tables, plus the v_products and v_order_lines views
  2. COPY        - data/products.csv and data/orders.csv
  3. queries.sql - Q01-Q14, each result saved to outputs/sql/ and all of them to outputs/sql/RESULTS.md

Connection: set DATABASE_URL, e.g. postgresql://postgres:postgres@localhost:5432/flipkart
"""
import io
import os
import re
from decimal import Decimal
from pathlib import Path

import pandas as pd
import psycopg2

HERE = Path(__file__).parent
ROOT = HERE.parent
OUT = ROOT / "outputs" / "sql"
OUT.mkdir(parents=True, exist_ok=True)
DSN = os.environ.get("DATABASE_URL", "postgresql://postgres:postgres@localhost:5432/flipkart")


def copy_df(cur, df, table):
    buf = io.StringIO()
    df.to_csv(buf, index=False, header=False)
    buf.seek(0)
    cur.copy_expert(f"COPY {table} ({', '.join(df.columns)}) FROM STDIN WITH (FORMAT csv)", buf)


def load(cur):
    cur.execute((HERE / "schema.sql").read_text())
    p = pd.read_csv(ROOT / "data" / "products.csv")
    p["flipkart_assured"] = p["flipkart_assured"].eq("Yes")
    copy_df(cur, p, "products")
    o = pd.read_csv(ROOT / "data" / "orders.csv")
    o["returned"] = o["returned"].eq("Yes")
    copy_df(cur, o, "orders")


def queries():
    parts = re.split(r"^-- (Q\d{2}) \| (.+?) \| (.+?)$", (HERE / "queries.sql").read_text(), flags=re.M)
    return [{"id": parts[i], "title": parts[i + 1].strip(), "question": parts[i + 2].strip(),
             "sql": parts[i + 3].strip()} for i in range(1, len(parts), 4)]


def main():
    conn = psycopg2.connect(DSN)
    conn.autocommit = True
    cur = conn.cursor()
    load(cur)
    md = ["# SQL Query Results\n", "PostgreSQL 16 · 2,000 products · 25,000 order lines (synthetic, 2025) · generated by `sql/run_sql.py`\n"]
    for q in queries():
        cur.execute(q["sql"])
        df = pd.DataFrame(cur.fetchall(), columns=[c[0] for c in cur.description])
        for col in df:
            if df[col].map(lambda v: isinstance(v, Decimal)).any():
                df[col] = df[col].astype(float)
        df.to_csv(OUT / f"{q['id'].lower()}.csv", index=False)
        md.append(f"## {q['id']}. {q['title']}\n\n*{q['question']}*\n\n```sql\n{q['sql']}\n```\n\n{df.to_markdown(index=False)}\n")
        print(f"{q['id']} {q['title']}: {len(df)} rows")
    (OUT / "RESULTS.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
