"""
Loads the IPL data into PostgreSQL and runs the 15 SQL queries.

  1. schema.sql  - tables, lookup tables for renamed teams and venues
  2. COPY        - data/Match_Info.csv and data/Ball_By_Ball_Match_Data.csv.gz into matches and deliveries
  3. clean.sql   - team and venue renames, plus the v_balls and v_innings views
  4. queries.sql - Q01-Q15, each result saved to outputs/sql/ and all of them to outputs/sql/RESULTS.md

Connection: set DATABASE_URL, e.g. postgresql://postgres:postgres@localhost:5432/ipl
"""
import io
import os
import re
from decimal import Decimal
from pathlib import Path

import pandas as pd
import psycopg2

HERE = Path(__file__).parent
ROOT = HERE.parent
OUT = ROOT / "outputs" / "sql"
OUT.mkdir(parents=True, exist_ok=True)
DSN = os.environ.get("DATABASE_URL", "postgresql://postgres:postgres@localhost:5432/ipl")


def copy_df(cur, df, table):
    buf = io.StringIO()
    df.to_csv(buf, index=False, header=False)
    buf.seek(0)
    cur.copy_expert(f"COPY {table} ({', '.join(df.columns)}) FROM STDIN WITH (FORMAT csv)", buf)


def load(cur):
    cur.execute((HERE / "schema.sql").read_text())
    m = pd.read_csv(ROOT / "data" / "Match_Info.csv")
    m = m.rename(columns={"match_number": "match_id", "eliminator": "super_over_winner"})[
        ["match_id", "match_date", "team1", "team2", "toss_winner", "toss_decision", "result",
         "super_over_winner", "winner", "player_of_match", "venue", "city"]]
    copy_df(cur, m, "matches")
    d = pd.read_csv(ROOT / "data" / "Ball_By_Ball_Match_Data.csv.gz")
    d = d.rename(columns={"ID": "match_id", "Innings": "innings", "Overs": "over_no", "BallNumber": "ball_no",
                          "Batter": "batter", "Bowler": "bowler", "NonStriker": "non_striker",
                          "ExtraType": "extra_type", "BatsmanRun": "batter_runs", "ExtrasRun": "extra_runs",
                          "TotalRun": "total_runs", "IsWicketDelivery": "is_wicket", "PlayerOut": "player_out",
                          "Kind": "dismissal_kind", "BattingTeam": "batting_team"})
    d["is_wicket"] = d["is_wicket"].astype(bool)
    d = d[["match_id", "innings", "over_no", "ball_no", "batter", "bowler", "non_striker", "extra_type",
           "batter_runs", "extra_runs", "total_runs", "is_wicket", "player_out", "dismissal_kind", "batting_team"]]
    copy_df(cur, d, "deliveries")
    cur.execute((HERE / "clean.sql").read_text())


def queries():
    parts = re.split(r"^-- (Q\d{2}) \| (.+?) \| (.+?)$", (HERE / "queries.sql").read_text(), flags=re.M)
    return [{"id": parts[i], "title": parts[i + 1].strip(), "question": parts[i + 2].strip(),
             "sql": parts[i + 3].strip()} for i in range(1, len(parts), 4)]


def main():
    conn = psycopg2.connect(DSN)
    conn.autocommit = True
    cur = conn.cursor()
    load(cur)
    cur.execute("SELECT (SELECT COUNT(*) FROM matches), (SELECT COUNT(*) FROM deliveries)")
    n_m, n_d = cur.fetchone()
    md = ["# SQL Query Results\n", f"PostgreSQL 16 · {n_m:,} matches · {n_d:,} deliveries · generated by `sql/run_sql.py`\n"]
    for q in queries():
        cur.execute(q["sql"])
        df = pd.DataFrame(cur.fetchall(), columns=[c[0] for c in cur.description])
        for col in df:
            if df[col].map(lambda v: isinstance(v, Decimal)).any():
                df[col] = df[col].astype(float)
        df.to_csv(OUT / f"{q['id'].lower()}.csv", index=False)
        md.append(f"## {q['id']}. {q['title']}\n\n*{q['question']}*\n\n```sql\n{q['sql']}\n```\n\n{df.to_markdown(index=False)}\n")
        print(f"{q['id']} {q['title']}: {len(df)} rows")
    (OUT / "RESULTS.md").write_text("\n".join(md))
    print(f"loaded {n_m} matches, {n_d} deliveries")


if __name__ == "__main__":
    main()
