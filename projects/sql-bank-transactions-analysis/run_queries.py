"""
Builds the database and runs every query in queries.sql.

  1. Creates the tables and view (schema.sql) and loads the CSV files with COPY.
  2. Times a query with EXPLAIN ANALYZE before and after adding indexes (indexes.sql).
  3. Runs Q01-Q20 and writes each result to outputs/ (CSV), plus outputs/RESULTS.md with the
     SQL and its result, three charts and summary.json.

Connection: set DATABASE_URL, e.g. postgresql://postgres:postgres@localhost:5432/bank
"""
import json
import os
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
import psycopg2  # noqa: E402

HERE = Path(__file__).parent
OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)
DSN = os.environ.get("DATABASE_URL", "postgresql://postgres:postgres@localhost:5432/bank")
WINE, ROSE, GREY = "#701A3D", "#C77B9B", "#8A8A8A"

BENCH = """SELECT t.txn_ts, t.amount FROM transactions t
WHERE t.account_id = 100250 AND t.txn_ts >= '2025-01-01' ORDER BY t.txn_ts"""


def load(cur):
    cur.execute((HERE / "schema.sql").read_text())
    for table in ["branches", "customers", "accounts", "transactions"]:
        with open(HERE / "data" / f"{table}.csv") as f:
            cur.copy_expert(f"COPY {table} FROM STDIN WITH (FORMAT csv, HEADER true)", f)


def explain_ms(cur, sql):
    cur.execute("EXPLAIN (ANALYZE, FORMAT JSON) " + sql)
    plan = cur.fetchone()[0][0]
    node = plan["Plan"]
    while node.get("Plans") and node["Node Type"] in ("Sort", "Limit"):
        node = node["Plans"][0]
    return plan["Execution Time"], node["Node Type"]


def parse_queries():
    text = (HERE / "queries.sql").read_text()
    parts = re.split(r"^-- (Q\d{2}) \| (.+?) \| (.+?)$", text, flags=re.M)
    out = []
    for i in range(1, len(parts), 4):
        out.append({"id": parts[i], "title": parts[i + 1].strip(), "question": parts[i + 2].strip(),
                    "sql": parts[i + 3].strip()})
    return out


def main():
    conn = psycopg2.connect(DSN)
    conn.autocommit = True
    cur = conn.cursor()
    load(cur)
    for _ in range(3):  # warm cache
        explain_ms(cur, BENCH)
    before = explain_ms(cur, BENCH)
    cur.execute((HERE / "indexes.sql").read_text())
    after = explain_ms(cur, BENCH)

    results, md = {}, ["# Query Results\n",
                       f"Generated by `run_queries.py` on PostgreSQL. Index test: the same lookup ran in "
                       f"**{before[0]:.2f} ms** ({before[1]}) before indexes and **{after[0]:.2f} ms** ({after[1]}) after.\n"]
    for q in parse_queries():
        cur.execute(q["sql"])
        df = pd.DataFrame(cur.fetchall(), columns=[d[0] for d in cur.description])
        for col in df:
            if df[col].dtype == object and df[col].map(lambda v: hasattr(v, "as_integer_ratio") and not isinstance(v, (int, float))).any():
                df[col] = df[col].astype(float)  # Decimal -> float
        results[q["id"]] = df
        df.to_csv(OUT / f"{q['id'].lower()}.csv", index=False)
        shown = df if len(df) <= 30 else df.head(30)
        md.append(f"## {q['id']}. {q['title']}\n\n*{q['question']}*\n\n```sql\n{q['sql']}\n```\n\n"
                  f"{shown.to_markdown(index=False)}\n" + (f"\n_{len(df)} rows; first 30 shown._\n" if len(df) > 30 else ""))
    (OUT / "RESULTS.md").write_text("\n".join(md))

    # charts
    m = results["Q06"]
    fig, ax = plt.subplots(figsize=(10, 4.5))
    x = range(len(m))
    ax.bar([i - 0.2 for i in x], m["credits_cr"], 0.4, color=WINE, label="Credits")
    ax.bar([i + 0.2 for i in x], m["debits_cr"], 0.4, color=ROSE, label="Debits")
    ax.set_xticks(list(x)[::3], m["month"][::3], rotation=45, ha="right")
    ax.set(ylabel="₹ crore", title="Monthly credits and debits")
    ax.legend()
    ax.spines[["top", "right"]].set_visible(False)
    fig.savefig(OUT / "chart_monthly_flows.png", dpi=130, bbox_inches="tight")
    plt.close(fig)

    c = results["Q03"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.barh(c["channel"][::-1], c["share_of_txns_pct"][::-1], color=WINE)
    ax.set(xlabel="Share of transactions (%)", title="Transactions by channel")
    ax.spines[["top", "right"]].set_visible(False)
    fig.savefig(OUT / "chart_channels.png", dpi=130, bbox_inches="tight")
    plt.close(fig)

    d = results["Q13"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.bar(d["decile"].astype(str), d["share_pct"], color=[WINE] + [ROSE] * 9)
    ax.set(xlabel="Customer decile by balance (1 = richest 10%)", ylabel="Share of balances (%)", title="Balance concentration")
    ax.spines[["top", "right"]].set_visible(False)
    fig.savefig(OUT / "chart_concentration.png", dpi=130, bbox_inches="tight")
    plt.close(fig)

    t = results["Q01"].set_index("table_name")["rows"]
    summary = {
        "rows": t.to_dict(),
        "index_test_ms": {"before": round(before[0], 3), "after": round(after[0], 3),
                          "plan_before": before[1], "plan_after": after[1]},
        "top_channel": c.iloc[0].to_dict(),
        "top10pct_balance_share": float(d.loc[0, "share_pct"]),
        "dormant_accounts": int(results["Q15"]["dormant_accounts"].sum()),
        "reactivated_dormant_alerts": len(results["Q16"]),
        "structuring_customers": len(results["Q17"]),
        "high_risk_outsized_inflow_customers": len(results["Q18"]),
        "festive": results["Q08"].to_dict(orient="records"),
        "upi_share_first_last": [float(results["Q12"]["upi_share_pct"].iloc[0]), float(results["Q12"]["upi_share_pct"].iloc[-1])],
    }
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2, default=str))
    print(json.dumps(summary, indent=2, default=str))


if __name__ == "__main__":
    main()
