"""
Builds the database and runs every query in queries.sql.

  1. Creates the tables and view (schema.sql) and loads data/*.csv with COPY.
  2. Runs Q01-Q18 and writes each result to outputs/ (CSV), plus outputs/RESULTS.md
     with the SQL and its result, three charts and summary.json.

Run clean_data.py first if data/ does not yet hold the three cleaned CSV files.
Connection: set DATABASE_URL, e.g. postgresql://postgres:postgres@localhost:5432/zomato
"""
import json
import os
import re
from decimal import Decimal
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
import psycopg2  # noqa: E402

HERE = Path(__file__).parent
OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)
DSN = os.environ.get("DATABASE_URL", "postgresql://postgres:postgres@localhost:5432/zomato")
RED, ROSE, GREY = "#B3263E", "#E8A0AC", "#8A8A8A"


def load(cur):
    cur.execute((HERE / "schema.sql").read_text())
    for table in ["countries", "restaurants", "restaurant_cuisines"]:
        with open(HERE / "data" / f"{table}.csv", encoding="utf-8") as f:
            cur.copy_expert(f"COPY {table} FROM STDIN WITH (FORMAT csv, HEADER true)", f)


def parse_queries():
    text = (HERE / "queries.sql").read_text()
    parts = re.split(r"^-- (Q\d{2}) \| (.+?) \| (.+?)$", text, flags=re.M)
    return [{"id": parts[i], "title": parts[i + 1].strip(), "question": parts[i + 2].strip(),
             "sql": parts[i + 3].strip()} for i in range(1, len(parts), 4)]


def tidy(df):
    for col in df:
        if df[col].map(lambda v: isinstance(v, Decimal)).any():
            df[col] = df[col].astype(float)
    return df


def style(ax):
    ax.spines[["top", "right"]].set_visible(False)


def main():
    conn = psycopg2.connect(DSN)
    conn.autocommit = True
    cur = conn.cursor()
    load(cur)

    results, md = {}, ["# Query Results\n", "Generated by `run_queries.py` on PostgreSQL 16 from the cleaned Zomato data.\n"]
    for q in parse_queries():
        cur.execute(q["sql"])
        df = tidy(pd.DataFrame(cur.fetchall(), columns=[d[0] for d in cur.description]))
        results[q["id"]] = df
        df.to_csv(OUT / f"{q['id'].lower()}.csv", index=False)
        md.append(f"## {q['id']}. {q['title']}\n\n*{q['question']}*\n\n```sql\n{q['sql']}\n```\n\n"
                  f"{df.to_markdown(index=False)}\n")
    (OUT / "RESULTS.md").write_text("\n".join(md))

    c = results["Q04"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.barh(c["cuisine"][::-1], c["pct_of_restaurants"][::-1], color=RED)
    ax.set(xlabel="Share of Indian restaurants serving it (%)", title="Most common cuisines in India")
    style(ax)
    fig.savefig(OUT / "chart_top_cuisines.png", dpi=130, bbox_inches="tight")
    plt.close(fig)

    p = results["Q06"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.bar(p["price_range"].astype(str), p["avg_rating"], color=[ROSE, ROSE, RED, RED])
    for x, (r, v) in enumerate(zip(p["avg_rating"], p["pct_rated_4_plus"])):
        ax.text(x, r + 0.03, f"{r:.2f}\n{v:.0f}% rated 4+", ha="center", fontsize=9)
    ax.set(ylim=(2.5, 4.3), xlabel="Price range (1 = cheapest, 4 = most expensive)", ylabel="Average rating",
           title="Ratings rise with price range")
    style(ax)
    fig.savefig(OUT / "chart_price_vs_rating.png", dpi=130, bbox_inches="tight")
    plt.close(fig)

    d = results["Q07"]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    x = range(len(d))
    ax.bar([i - 0.2 for i in x], d["rating_with_delivery"], 0.4, color=RED, label="Online delivery")
    ax.bar([i + 0.2 for i in x], d["rating_without_delivery"], 0.4, color=GREY, label="No online delivery")
    ax.set_xticks(list(x), d["price_range"].astype(str))
    ax.set(ylim=(2.5, 4.3), xlabel="Price range", ylabel="Average rating", title="Delivery vs no delivery, by price range")
    ax.legend(frameon=False)
    style(ax)
    fig.savefig(OUT / "chart_delivery.png", dpi=130, bbox_inches="tight")
    plt.close(fig)

    q1, q2, q3 = results["Q01"], results["Q02"], results["Q03"]
    summary = {
        "restaurants": int(q1["restaurants"].sum()),
        "countries": len(q1),
        "india": q1[q1["country"] == "India"].to_dict(orient="records")[0],
        "top_cities": q2.head(4).to_dict(orient="records"),
        "not_rated_india": q3[q3["rating_text"] == "Not rated"].to_dict(orient="records"),
        "top_cuisines": results["Q04"].head(3).to_dict(orient="records"),
        "best_cuisines": results["Q05"].head(3).to_dict(orient="records"),
        "price_range": p.to_dict(orient="records"),
        "delivery": d.to_dict(orient="records"),
        "booking": results["Q08"].to_dict(orient="records"),
        "correlations": results["Q14"].to_dict(orient="records")[0],
        "chains": results["Q09"].head(5).to_dict(orient="records"),
    }
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2, default=str))
    print(json.dumps(summary, indent=2, default=str))


if __name__ == "__main__":
    main()
